// Helper: Find relevant scriptures for a user's question/mood
// Returns top N most relevant entries
// ─────────────────────────────────────────────────────────────────────────────
export function findRelevantScriptures(query, mood = "", maxResults = 5) {
  const searchText = `${query} ${mood}`.toLowerCase();
  const words = searchText.split(/\s+/).filter(w => w.length > 2);

  const scored = SCRIPTURES.map(scripture => {
    let score = 0;
    const searchableText = [
      ...scripture.emotions,
      ...scripture.themes,
      scripture.translation,
      scripture.commentary
    ].join(" ").toLowerCase();

    for (const word of words) {
      if (scripture.emotions.some(e => e.includes(word) || word.includes(e))) score += 3;
      if (scripture.themes.some(t => t.includes(word) || word.includes(t))) score += 2;
      if (searchableText.includes(word)) score += 1;
    }

    return { scripture, score };
  });

  return scored
    .filter(s => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, maxResults)
    .map(s => s.scripture);
}

// ─────────────────────────────────────────────────────────────────────────────
// Helper: Build the scripture context block to inject into Grok's system prompt
// ─────────────────────────────────────────────────────────────────────────────
export function buildScriptureContext(relevantScriptures) {
  if (!relevantScriptures.length) return "";

  const entries = relevantScriptures.map(s => {
    const source = s.book_name && s.chapter && s.verse_number
      ? `${s.book_name} ${s.chapter}.${s.verse_number}`
      : s.source || "Scripture";

    const sanskritText = s.sanskrit_text ?? s.verse_sanskrit ?? "";
    const englishTranslation = s.english_translation ?? s.translation ?? "";
    const transliteration = s.transliteration ?? "";
    const commentary = s.commentary ?? "";
    const themes = Array.isArray(s.themes) ? s.themes : [];

    return `[${source}]
Sanskrit: ${sanskritText}
Transliteration: ${transliteration}
Translation: ${englishTranslation}
Commentary: ${commentary}
Themes: ${themes.join(", ")}`;
  }).join("\n\n---\n\n");

  return `\n\nRETRIEVED SCRIPTURE PASSAGES:\n\n${entries}\n\nDraw primarily from these scriptures in your response. Quote them accurately. If a passage is not relevant, do not force it into the answer.`;
}
